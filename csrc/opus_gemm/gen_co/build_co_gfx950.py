"""Offline builder for the gfx950 pre-compiled (.co) opus_gemm kernels.

The a4w4_mxfp4_nt pipeline pins its A / B / C fragments with [[clang::amdgpu_pin_agpr/vgpr]]; only the pin
toolchain (clang 24 + amdgpu pin patches) compiles it, and stock ROCm hipcc used by the aiter JIT does not.
So the device code is compiled ahead of time here (one bare ELF code object per kernel) and loaded at runtime by
include/gfx950/opus_co_launch_mxfp4_gfx950.cuh; the host launchers / dispatch go through the ordinary JIT.

Source of truth: gen_co/co_kernels_gfx950.json. Names: <name>.co == extern "C" symbol == host launcher symbol, with
name = opus_gemm_gfx950_<pipeline>_co_<B_M>x<B_N>x<B_K>  (see kernel_name()).

The toolchain is not pinned; the resolved clang, its version, flags and per-kernel metadata (registers, spills,
LDS, sha256) are recorded in gen_co/gfx950/build_info.json.

Usage:
    python3 csrc/opus_gemm/gen_co/build_co_gfx950.py --llvm-bin /path/to/pin-toolchain/bin \\
        --opus-include /path/to/csrc/include      # an opus that builds with that toolchain
"""
import argparse, datetime, hashlib, json, os, re, shutil, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
OPUS_GEMM_DIR = os.path.dirname(HERE)
INCLUDE_DIR = os.path.join(OPUS_GEMM_DIR, "include")
JSON = os.path.join(HERE, "co_kernels_gfx950.json")
OUT_DIR = os.path.join(HERE, "gfx950")

STUB = """// generated by build_co_gfx950.py -- do not edit
#include <opus/hip_minimal.hpp>
#include "{header}"
extern "C" __global__ __launch_bounds__({lb0}, {lb1}) void {name}({kargs} kargs) {{
    {body}<{traits}>(kargs);
}}
"""


def kernel_name(e):
    m, n, k = e["tile"]
    return f"opus_gemm_gfx950_{e['pipeline']}_co_{m}x{n}x{k}"


def load_entries(path=JSON):
    return json.load(open(path))["gfx950"]


def notes(readelf, co):
    out = subprocess.run([readelf, "--notes", co], capture_output=True, text=True, check=True).stdout
    keys = ["vgpr_count", "agpr_count", "sgpr_count", "vgpr_spill_count", "sgpr_spill_count",
            "group_segment_fixed_size", "private_segment_fixed_size", "kernarg_segment_size"]
    r = {}
    for k in keys:
        m = re.search(r"\.%s:\s+(\d+)" % k, out)
        if m:
            r[k] = int(m.group(1))
    m = re.search(r"\.name:\s+(\S+)", out)
    r["symbol"] = m.group(1) if m else None
    return r


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--llvm-bin", default=os.environ.get("OPUS_CO_LLVM_BIN"), required=False)
    ap.add_argument("--opus-include", default=os.environ.get("OPUS_CO_OPUS_INCLUDE"))
    ap.add_argument("--only", nargs="*", help="kernel names to build (default: all)")
    ap.add_argument("--keep-asm", action="store_true", help="keep .s / .dis next to the images (asm/, gitignored)")
    a = ap.parse_args()
    if not a.llvm_bin or not a.opus_include:
        sys.exit("need --llvm-bin (pin toolchain) and --opus-include (opus that builds with it)")
    clang = os.path.join(a.llvm_bin, "clang++")
    readelf = os.path.join(a.llvm_bin, "llvm-readelf")
    objdump = os.path.join(a.llvm_bin, "llvm-objdump")
    version = subprocess.run([clang, "--version"], capture_output=True, text=True).stdout.splitlines()[0]
    os.makedirs(OUT_DIR, exist_ok=True)
    info_path = os.path.join(OUT_DIR, "build_info.json")
    info = json.load(open(info_path)) if os.path.isfile(info_path) else {"kernels": []}
    by_name = {k["name"]: k for k in info.get("kernels", [])}
    ok = True
    for e in load_entries():
        name = kernel_name(e)
        if a.only and name not in a.only:
            continue
        with tempfile.TemporaryDirectory() as td:
            src = os.path.join(td, name + ".cc")
            open(src, "w").write(STUB.format(header=e["pipeline_header"], lb0=e["launch_bounds"][0], lb1=e["launch_bounds"][1],
                                             name=name, kargs=e["kargs"], body=e["body_func"], traits=e["traits"]))
            co = os.path.join(td, name + ".co")
            cmd = [clang, "-x", "hip", src, "--offload-arch=gfx950", "--cuda-device-only", "-O3", "-std=c++17",
                   "-D__HIPCC_RTC__", f"-I{INCLUDE_DIR}", f"-I{os.path.join(INCLUDE_DIR, 'gfx950')}", f"-I{a.opus_include}",
                   *e["device_flags"], "-o", co]
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode:
                print(f"[FAIL] {name}\n{r.stderr[-4000:]}"); ok = False; continue
            if open(co, "rb").read(4) != b"\x7fELF":   # clang offload bundle -> bare amdhsa ELF (AiterAsmKernelFast needs it)
                bundler = os.path.join(a.llvm_bin, "clang-offload-bundler")
                subprocess.run([bundler, "--unbundle", "--type=o", "--targets=hipv4-amdgcn-amd-amdhsa--gfx950",
                                f"--input={co}", f"--output={co}.elf"], check=True)
                os.replace(co + ".elf", co)
            data = open(co, "rb").read()
            assert data[:4] == b"\x7fELF", "not a bare ELF code object"
            meta = notes(readelf, co)
            if meta.get("symbol") != name:
                print(f"[FAIL] {name}: symbol {meta.get('symbol')}"); ok = False; continue
            dst = os.path.join(OUT_DIR, name + ".co")
            shutil.copyfile(co, dst)
            if a.keep_asm:
                os.makedirs(os.path.join(OUT_DIR, "asm"), exist_ok=True)
                open(os.path.join(OUT_DIR, "asm", name + ".dis"), "w").write(
                    subprocess.run([objdump, "-d", "--mcpu=gfx950", dst], capture_output=True, text=True).stdout)
        rec = {"kid": e["kid"], "name": name, "image": name + ".co", "symbol": name, "pipeline": e["pipeline"],
               "tile": e["tile"], "traits": e["traits"], "co_sha256": hashlib.sha256(data).hexdigest(),
               "compiler": version, "llvm_bin": a.llvm_bin, "opus_include": a.opus_include,
               "device_flags": e["device_flags"], **{k: v for k, v in meta.items() if k != "symbol"},
               "zero_vgpr_spill": meta.get("vgpr_spill_count", 0) == 0 and meta.get("private_segment_fixed_size", 0) == 0}
        by_name[name] = rec
        print(f"[ok] {name}: vgpr {meta.get('vgpr_count')} agpr {meta.get('agpr_count')} vgpr_spill {meta.get('vgpr_spill_count')} "
              f"sgpr_spill {meta.get('sgpr_spill_count')} lds {meta.get('group_segment_fixed_size')} scratch {meta.get('private_segment_fixed_size')}")
    info = {"updated_utc": datetime.datetime.now(datetime.timezone.utc).isoformat(), "arch": "gfx950",
            "kernels": sorted(by_name.values(), key=lambda k: k["kid"])}
    json.dump(info, open(info_path, "w"), indent=2)
    sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
